#!/usr/bin/env python3
"""Quantize the agent's weight matrices to int4 (W4A16): per output row a
symmetric scale, weights as unsigned nibbles (q + 8), stored planar per row
(the first nin/2 bytes hold the low nibbles = weights 0..nin/2-1, the high
nibbles = weights nin/2..nin-1) so a vector kernel unpacks a byte into two
weights without a shuffle.  Writes model_w4.h/.bin and prompts_w4.h (the
dequantized numpy model's own outputs).  agent.c -DUSE_W4 dequantizes on the
vector unit inside the dot product: 8x fewer weight bytes than fp32."""
import pathlib
import argparse, os, re, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import train_agent_gpt as tr

def read_header(path):
    s = pathlib.Path(path).read_text()
    dims = {k: int(re.search(r'#define GPT_%s (\d+)' % k, s).group(1)) for k in ('D', 'L', 'H', 'T', 'V')}
    offs = {m.group(1).lower(): int(m.group(2)) for m in re.finditer(r'#define OFF_(\w+) (\d+)', s)}
    m = re.search(r'#define GPT_W_BLOB "([^"]+)"', s)
    if m:
        w = np.fromfile(os.path.join(os.path.dirname(path), m.group(1)), dtype=np.float32)
    else:
        body = s[s.index('static const float GPT_W'):]
        body = body[body.index('{') + 1:body.index('};')]
        w = np.array([float(t) for t in re.sub(r'/\*.*?\*/', '', body, flags=re.S).replace('\n', '').split(',') if t.strip()], dtype=np.float32)
    g = re.search(r'#define GEN_CALL (\d+)', s)
    tr.GEN_MAX = int(g.group(1)) if g else 24
    return dims, offs, w


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dir', default='test/llm-agent'); ap.add_argument('--questions', type=int, default=40)
    ap.add_argument('--prompts', type=int, default=8); ap.add_argument('--export-anyway', action='store_true')
    a = ap.parse_args()
    dims, offs, w = read_header(os.path.join(a.dir, 'model_weights.h'))
    D, L_, H, T, V = dims['D'], dims['L'], dims['H'], dims['T'], dims['V']
    model = tr.GPT(V, T, D, L_, H, np.random.default_rng(0))
    shapes = {'wte': (V, D), 'wpe': (T, D), 'lnf_g': (D,), 'lnf_b': (D,), 'head': (D, V)}
    for l in range(L_):
        shapes.update({'ln1_g%d' % l: (D,), 'ln1_b%d' % l: (D,), 'wqkv%d' % l: (D, 3 * D), 'bqkv%d' % l: (3 * D,), 'wo%d' % l: (D, D), 'bo%d' % l: (D,),
                       'ln2_g%d' % l: (D,), 'ln2_b%d' % l: (D,), 'w1%d' % l: (D, 4 * D), 'b1%d' % l: (4 * D,), 'w2%d' % l: (4 * D, D), 'b2%d' % l: (D,)})
    for k, shp in shapes.items():
        n = int(np.prod(shp)); arr = w[offs[k]:offs[k] + n]
        if len(shp) == 2 and k not in ('wte', 'wpe'):
            arr = arr.reshape(shp[1], shp[0]).T
        model.p[k] = np.ascontiguousarray(arr.reshape(shp)).astype(np.float32)
    def accuracy(m):
        erng = np.random.default_rng(1234); tests = []
        for _ in range(a.questions):
            ex = tr.make_example(erng)
            q = ex.split('\n')[0][3:]; want_call = ex.split('\n')[1][3:]; want = ex.split('\n')[3][3:]
            call, ans = tr.agent_episode(m, q)
            tests.append((q, want_call, want, call == want_call and ans == want, (call, ans)))
        return tests
    blob = bytearray(); offsets = {}
    for l in range(L_):
        for k in ('wqkv%d' % l, 'wo%d' % l, 'w1%d' % l, 'w2%d' % l):
            W = model.p[k].T.copy()                        # [out][in]
            nout, nin = W.shape; assert nin % 2 == 0
            scale = np.abs(W).max(1) / 7.0; scale[scale == 0] = 1.0
            q = np.clip(np.rint(W / scale[:, None]), -8, 7).astype(np.int32)
            What = (q * scale[:, None]).astype(np.float32)
            err = np.sqrt(((What - W) ** 2).mean()) / np.sqrt((W ** 2).mean())
            print('%-6s %4dx%-4d int4 relative rms error %.3f' % (k, nout, nin, err))
            u = (q + 8).astype(np.uint8)
            packed = (u[:, :nin // 2] | (u[:, nin // 2:] << 4)).astype(np.uint8)   # planar nibbles
            while len(blob) % 64: blob += b'\0'
            off_q = len(blob); blob += packed.tobytes()
            while len(blob) % 64: blob += b'\0'
            off_s = len(blob); blob += scale.astype(np.float32).tobytes()
            offsets[k] = (off_q, off_s, nout, nin)
            model.p[k] = np.ascontiguousarray(What.T).astype(np.float32)
    qt = accuracy(model); nok = sum(t[3] for t in qt); print('int4 model: %d/%d fresh questions right' % (nok, a.questions))
    chosen = [t for t in qt if t[3]][:a.prompts]
    if len(chosen) < a.prompts:
        if not a.export_anyway:
            sys.exit('fewer than %d correct episodes under the int4 model' % a.prompts)
        chosen = qt[:a.prompts]
    with open(os.path.join(a.dir, 'model_w4.h'), 'w') as f:
        f.write('/* Generated by tools/llm/quantize_w4.py -- do not edit.  int4 weights: per row a float32\n * scale and nin/2 bytes of planar nibbles (q+8; low nibbles = first half of the row,\n * high = second half) in model_w4.bin at the offsets below; agent.c .incbin\'s it as W4_BLOB. */\n')
        f.write('#define W4_BLOB_FILE "model_w4.bin"\n')
        for k, (oq, os_, nout, nin) in offsets.items():
            f.write('#define W4_OFF_Q_%s %d\n#define W4_OFF_S_%s %d\n' % (k.upper(), oq, k.upper(), os_))
    pathlib.Path(os.path.join(a.dir, 'model_w4.bin')).write_bytes(bytes(blob))
    with open(os.path.join(a.dir, 'prompts_w4.h'), 'w') as f:
        f.write('/* Generated by tools/llm/quantize_w4.py: questions the int4 numpy model answers with\n * greedy decoding, with its own outputs (what agent.c -DUSE_W4 must reproduce). */\n')
        f.write('#define N_PROMPTS %d\n' % len(chosen))
        f.write('static const char *const PROMPT_Q[N_PROMPTS] = { %s };\n' % ', '.join('"%s"' % t[0] for t in chosen))
        f.write('static const char *const PROMPT_CALL[N_PROMPTS] = { %s };\n' % ', '.join('"%s"' % t[1] for t in chosen))
        f.write('static const char *const PROMPT_CALL_MODEL[N_PROMPTS] = { %s };\n' % ', '.join('"%s"' % t[4][0] for t in chosen))
        f.write('static const char *const PROMPT_ANS_MODEL[N_PROMPTS] = { %s };\n' % ', '.join('"%s"' % t[4][1] for t in chosen))
        f.write('static const char *const PROMPT_ANS[N_PROMPTS] = { %s };\n' % ', '.join('"%s"' % t[2] for t in chosen))
    print('wrote %s/model_w4.h, model_w4.bin (%d bytes) and prompts_w4.h (%d prompts)' % (a.dir, len(blob), len(chosen)))

if __name__ == '__main__':
    main()
